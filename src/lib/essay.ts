export type ChatMsg = { role: "user" | "kadam"; text: string }

function localAdvice(question: string): string {
  const q = question.toLowerCase()
  if (/структ|план|начать|hook|начало|аутлайн/.test(q)) {
    return "Начни с конкретного момента, а не с общих слов «я всегда любил…». Структура: 1) сцена-крючок → 2) что ты сделал руками → 3) чему научился и как это связано с направлением. Один сильный пример лучше трёх поверхностных."
  }
  if (/эссе|motivation|мотива|why|почему/.test(q)) {
    return "Отвечай на «почему именно это и именно ты» через доказательства, а не заявления. Не «я увлечён IT», а «я собрал бота, который…». Конкретика = искренность, которую видно."
  }
  if (/грамм|англ|язык|перевод|слов/.test(q)) {
    return "Пиши простыми короткими предложениями — это читается как уверенность. Избегай тезаурус-слов, которые ты не используешь в речи: они выдают неестественность сильнее, чем простой язык."
  }
  return "Сформулируй мысль вокруг одной честной истории: что зацепило, что ты сделал, что понял. Убери общие фразы, оставь конкретные детали и цифры — они делают эссе живым."
}

export async function askLumifield(question: string, lang: Lang = "ru", context = ""): Promise<{ text: string; ai: boolean }> {
  const sys =
    "Ты — Lumi, дружелюбный маскот и помощник сервиса Lumifield AI для школьников Казахстана. Представляйся как Lumi, говори тепло и на «ты», без канцелярита; один уместный эмодзи на ответ — максимум. " +
    `Отвечай ТОЛЬКО на ${LANG_NAME[lang]} языке, конкретно и по делу. Ты помогаешь с двумя вещами:\n` +
    "1) ЭССЕ и академические вопросы: как сформулировать, структурировать, усилить мысль; расшифровка промптов, аутлайны, точный фидбэк на черновик. " +
    "Про то, что эссе нельзя писать через AI целиком, НЕ напоминай в каждом ответе — интерфейс уже показывает это отдельно; скажи один раз, только если человек прямо просит написать всё эссе за него.\n" +
    "2) ВОПРОСЫ ПО СЕРВИСУ Lumifield AI. Факты: каталог возможностей (олимпиады, гранты, курсы, стажировки) — бесплатный; AI-профориентация из 20 вопросов — нужна регистрация, результат сохраняется в профиле; " +
    "тарифы: Free — $0; Lumifield+ — $15/мес (персональный AI-план и карта поступления, подбор вузов, тест уровня IELTS/SAT/HSK с оценкой шансов, AI-разбор эссе); " +
    "Lumifield Pro — $50 раз в 6 месяцев (всё из Plus + вузы с дедлайнами и расширенный AI-разбор); промокод вводится на странице «Тарифы»; трекер заявок и дедлайнов — в аккаунте. " +
    "Если не знаешь ответа про сервис — честно скажи и предложи написать на почту поддержки."
  const answer = await chat(
    [{ role: "system", content: sys }, { role: "user", content: (context ? `Контекст: ${context}\n\n` : "") + question }],
    { temperature: 0.6, max_tokens: 700, task: "assist" },
  )
  if (!answer || !answer.trim()) return { text: localAdvice(question), ai: false }
  return { text: answer.trim(), ai: true }
}
